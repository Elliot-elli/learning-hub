"""Build each site into its own self-contained, independently deployable folder.

Usage:
    python tools/build.py            build every site
    python tools/build.py ap         build one site only
    python tools/build.py --check    report whether the content compiles

Layout:
    content/sites/<site>.json     site configuration (name, subjects, sections)
    content/modules/*.json        flashcard decks, shared across sites
    assets/                       shared front end (engine, styles, app)
    templates/                    page templates
    site/<site>/                  build output, one deployable folder per site

Every site folder carries its own copy of the shared assets, so a single
folder can be deployed on its own. The source of truth stays in content/,
assets/ and templates/, and is never duplicated there.

The deck data is compiled to a synchronous <script src> rather than fetched:
the engine reads window.AP_MODULES while it executes, so the binding order
must not depend on a network round trip. This also keeps the pages usable
when opened straight from disk.
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content')
SITES = os.path.join(CONTENT, 'sites')
MODULES = os.path.join(CONTENT, 'modules')
ASSETS = os.path.join(ROOT, 'assets')
TEMPLATES = os.path.join(ROOT, 'templates')
DIST = os.path.join(ROOT, 'site')

BANNER = ('// Generated by tools/build.py from content/. Do not edit by hand.\n'
          '// Re-run the build after changing any JSON in content/.\n')

# Files copied into every site folder. The engine and the flashcard
# stylesheet are game assets: they ship byte for byte and are never edited
# here. See tools/game-baseline.json.
SHARED_CSS = ['tokens.css', 'shell.css', 'flashcards.css', 'theme-flashcards.css']
SHARED_JS = ['engine.js', 'site.js', 'player.js']

# Pages each site publishes. The flashcards page carries its own layout.
# The subject page reads its subject from the URL, so no page needs a
# per-subject copy.
SITE_PAGES = [
    ('index.html', 'overview'),
    ('courses.html', 'courses'),
    ('subject.html', 'subject'),
    ('review.html', 'review'),
]


def load_json(path):
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def deck_stats(deck):
    """Card count, chapter count and the cards per chapter."""
    chapters = []
    for section in deck.get('sections', []):
        for level in section.get('levels', []):
            chapters.append(len(level.get('cards', [])))
    return {
        'cards': sum(chapters),
        'chapters': len(chapters),
        'chapterCards': chapters,
    }


def collect():
    """Return the site configs and the decks they reference."""
    if not os.path.isdir(SITES):
        raise SystemExit('missing content directory: content/sites')

    sites = []
    for name in sorted(os.listdir(SITES)):
        if not name.endswith('.json'):
            continue
        site = load_json(os.path.join(SITES, name))
        site['_file'] = name
        sites.append(site)

    decks = {}
    for name in sorted(os.listdir(MODULES)):
        if name.endswith('.json'):
            decks[name[:-5]] = load_json(os.path.join(MODULES, name))
    return sites, decks


def validate(sites, decks):
    """Fail the build on anything that would corrupt a learner's archive."""
    problems = []
    site_ids = set()
    for site in sites:
        sid = site.get('id')
        if not sid:
            problems.append('site without id: ' + site['_file'])
            continue
        if sid in site_ids:
            problems.append('duplicate site id: ' + sid)
        site_ids.add(sid)

        subject_ids = set()
        store_keys = {}
        for subject in site.get('subjects', []):
            if subject.get('id') in subject_ids:
                problems.append('duplicate subject id %s in %s'
                                % (subject.get('id'), sid))
            subject_ids.add(subject.get('id'))

            section_ids = set()
            for section in subject.get('sections', []):
                if section.get('id') in section_ids:
                    problems.append('duplicate section id %s in %s'
                                    % (section.get('id'), sid))
                section_ids.add(section.get('id'))

                mid = section.get('module')
                deck = decks.get(mid)
                if deck is None:
                    problems.append('unknown module %s in %s' % (mid, sid))
                    continue
                if deck.get('id') != mid:
                    problems.append('deck id mismatch: %s != %s'
                                    % (deck.get('id'), mid))
                key = deck.get('storeKey')
                if not key:
                    problems.append('deck without storeKey: ' + mid)
                elif key in store_keys:
                    problems.append('duplicate storeKey %s: %s and %s'
                                    % (key, store_keys[key], mid))
                else:
                    store_keys[key] = mid

                terms = []
                for chapter in deck.get('sections', []):
                    for level in chapter.get('levels', []):
                        for card in level.get('cards', []):
                            if not card.get('term') or not card.get('definition'):
                                problems.append('card without term/definition in ' + mid)
                            terms.append(card.get('term'))
                dupes = sorted({t for t in terms if terms.count(t) > 1})
                if dupes:
                    problems.append('duplicate terms in %s: %s'
                                    % (mid, ', '.join(dupes)))

    if problems:
        raise SystemExit('content validation failed:\n  - '
                         + '\n  - '.join(problems))


def build_site_data(site, decks):
    """The site description handed to the front end."""
    out = {
        'id': site['id'],
        'name': site['name'],
        'brand': site['brand'],
        'tagline': site['tagline'],
        'description': site['description'],
        'subjects': [],
    }
    for subject in site.get('subjects', []):
        entry = {
            'id': subject['id'],
            'title': subject['title'],
            'description': subject.get('description', ''),
            'sections': [],
        }
        for section in subject.get('sections', []):
            deck = decks[section['module']]
            info = deck_stats(deck)
            entry['sections'].append({
                'id': section['id'],
                'title': section['title'],
                'module': section['module'],
                'storeKey': deck['storeKey'],
                'cards': info['cards'],
                'chapters': info['chapters'],
                'chapterCards': info['chapterCards'],
                'deckTitle': deck.get('title', ''),
                'subjectLine': deck.get('subjectLine', ''),
            })
        out['subjects'].append(entry)
    return out


def write_if_changed(path, text):
    """Write only when the content differs, so rebuilds stay quiet."""
    if os.path.exists(path):
        with open(path, encoding='utf-8') as fh:
            if fh.read() == text:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    return True


def copy_if_changed(src, dst):
    """Copy a shared asset, skipping the write when bytes already match."""
    with open(src, 'rb') as fh:
        blob = fh.read()
    if os.path.exists(dst):
        with open(dst, 'rb') as fh:
            if fh.read() == blob:
                return False
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, 'wb') as fh:
        fh.write(blob)
    return True


def render(template, mapping, target):
    """Fill a template and write it to target."""
    with open(os.path.join(TEMPLATES, template), encoding='utf-8') as fh:
        html = fh.read()
    for key, value in mapping.items():
        html = html.replace('@@' + key + '@@', value)
    if '@@' in html:
        raise SystemExit('unfilled placeholder in ' + template)
    write_if_changed(target, html)


def build_site(site, decks):
    """Produce one self-contained folder for a site."""
    sid = site['id']
    out = os.path.join(DIST, sid)
    changed = []

    data = build_site_data(site, decks)
    site_js = BANNER + 'window.LH_SITE = %s;\n' % json.dumps(
        data, ensure_ascii=False, indent=2)
    path = os.path.join(out, 'assets', 'data', 'site.js')
    if write_if_changed(path, site_js):
        changed.append(os.path.relpath(path, ROOT))

    used = []
    for subject in site.get('subjects', []):
        for section in subject.get('sections', []):
            mid = section['module']
            if mid not in used:
                used.append(mid)
    modules_js = BANNER + 'window.AP_MODULES = %s;\n' % json.dumps(
        {mid: decks[mid] for mid in used}, ensure_ascii=False, indent=2)
    path = os.path.join(out, 'assets', 'data', 'modules.js')
    if write_if_changed(path, modules_js):
        changed.append(os.path.relpath(path, ROOT))

    for name in SHARED_CSS:
        src = os.path.join(ASSETS, 'css', name)
        dst = os.path.join(out, 'assets', 'css', name)
        if copy_if_changed(src, dst):
            changed.append(os.path.relpath(dst, ROOT))

    for name in SHARED_JS:
        src = os.path.join(ASSETS, 'js', name)
        dst = os.path.join(out, 'assets', 'js', name)
        if copy_if_changed(src, dst):
            changed.append(os.path.relpath(dst, ROOT))

    for filename, view in SITE_PAGES:
        mapping = {
            'SITE_ID': sid,
            'SITE_NAME': site['name'],
            'BRAND': site['brand'],
            'TAGLINE': site['tagline'],
            'DESCRIPTION': site['description'],
            'VIEW': view,
        }
        render('site.html', mapping, os.path.join(out, filename))
        changed.append(os.path.relpath(os.path.join(out, filename), ROOT))

    render('flashcards.html', {
        'SITE_ID': sid,
        'SITE_NAME': site['name'],
        'BRAND': site['brand'],
    }, os.path.join(out, 'flashcards.html'))
    changed.append(os.path.relpath(os.path.join(out, 'flashcards.html'), ROOT))

    return changed


def main():
    sites, decks = collect()
    validate(sites, decks)

    wanted = [a for a in sys.argv[1:] if not a.startswith('-')]
    if wanted:
        sites = [s for s in sites if s['id'] in wanted]
        if not sites:
            raise SystemExit('no such site: ' + ', '.join(wanted))

    all_changed = []
    for site in sites:
        all_changed += build_site(site, decks)

    for rel in all_changed:
        print('wrote', rel)
    print('%d files written' % len(all_changed))

    if '--check' in sys.argv:
        print('content compiles clean')


if __name__ == '__main__':
    main()
