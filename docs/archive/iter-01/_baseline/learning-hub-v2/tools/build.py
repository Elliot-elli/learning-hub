"""Compile content/*.json into synchronously loaded data scripts and pages.

Content lives in content/ as JSON so an AI agent can edit cards without
touching HTML or engine code. The engine reads window.AP_MODULES at script
execution time, so the compiled output is loaded with a synchronous
<script src> instead of fetch(). fetch() would resolve after the engine
boots and would break the timing contract the archive depends on.

Usage:
    python tools/build.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, 'content')
DATA = os.path.join(ROOT, 'assets', 'data')
TEMPLATES = os.path.join(ROOT, 'tools', 'templates')

BANNER = ('// Generated by tools/build.py from content/. Do not edit by hand.\n'
          '// Re-run the build after changing any JSON in content/.\n')


def load(rel):
    with open(os.path.join(CONTENT, rel), encoding='utf-8') as fh:
        return json.load(fh)


def collect():
    """Return (manifest, {programme: {module_id: module_data}})."""
    manifest = load('manifest.json')
    modules = {}
    for programme in manifest['programmes']:
        pid = programme['id']
        modules[pid] = {}
        for subject in programme['subjects']:
            for section in subject['sections']:
                mid = section['module']
                rel = os.path.join(pid, mid + '.json')
                if not os.path.exists(os.path.join(CONTENT, rel)):
                    raise SystemExit('missing content file: content/' + rel.replace('\\', '/'))
                modules[pid][mid] = load(rel)
    return manifest, modules


def stats(module):
    """Card count, chapter count and per-chapter card counts."""
    chapters = []
    for sec in module['sections']:
        for level in sec['levels']:
            chapters.append(len(level['cards']))
    return {
        'cards': sum(chapters),
        'chapters': len(chapters),
        'chapterCards': chapters,
    }


def validate(manifest, modules):
    """Fail the build on anything that would corrupt a learner's archive."""
    problems = []
    seen_keys = {}
    for programme in manifest['programmes']:
        pid = programme['id']
        for subject in programme['subjects']:
            for section in subject['sections']:
                mid = section['module']
                module = modules[pid].get(mid)
                if module is None:
                    problems.append('unregistered module: ' + mid)
                    continue
                if module.get('id') != mid:
                    problems.append('module id mismatch: %s != %s'
                                    % (module.get('id'), mid))
                key = module.get('storeKey')
                if not key:
                    problems.append('module without storeKey: ' + mid)
                    continue
                if key in seen_keys:
                    problems.append('duplicate storeKey %s: %s and %s'
                                    % (key, seen_keys[key], mid))
                seen_keys[key] = mid
                terms = []
                for sec in module['sections']:
                    for level in sec['levels']:
                        for card in level['cards']:
                            if not card.get('term') or not card.get('definition'):
                                problems.append('card without term/definition in ' + mid)
                            terms.append(card['term'])
                dupes = {t for t in terms if terms.count(t) > 1}
                if dupes:
                    problems.append('duplicate terms in %s: %s'
                                    % (mid, ', '.join(sorted(dupes))))
    if problems:
        raise SystemExit('content validation failed:\n  - '
                         + '\n  - '.join(problems))


def build_manifest_js(manifest, modules, programmes):
    """Manifest slice for a set of programmes, with module stats filled in."""
    out = {
        'site': manifest['site'],
        'activities': manifest['activities'],
        'programmes': [],
    }
    for programme in manifest['programmes']:
        if programme['id'] not in programmes:
            continue
        entry = {
            'id': programme['id'],
            'title': programme['title'],
            'short': programme['short'],
            'desc': programme['desc'],
            'subjects': [],
        }
        for subject in programme['subjects']:
            subj = {
                'id': subject['id'],
                'title': subject['title'],
                'desc': subject['desc'],
                'sections': [],
            }
            for section in subject['sections']:
                module = modules[programme['id']][section['module']]
                info = stats(module)
                subj['sections'].append({
                    'id': section['id'],
                    'title': section['title'],
                    'desc': section['desc'],
                    'module': section['module'],
                    'storeKey': module['storeKey'],
                    'cards': info['cards'],
                    'chapters': info['chapters'],
                    'chapterCards': info['chapterCards'],
                    'subjectLine': module.get('subjectLine', ''),
                })
            entry['subjects'].append(subj)
        out['programmes'].append(entry)
    return out


def write_if_changed(path, text):
    """Avoid touching mtime when content is unchanged."""
    if os.path.exists(path):
        with open(path, encoding='utf-8') as fh:
            if fh.read() == text:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    return True


def render(template, mapping, target):
    """Fill a template and write it to target."""
    with open(os.path.join(TEMPLATES, template), encoding='utf-8') as fh:
        html = fh.read()
    for key, value in mapping.items():
        html = html.replace('@@' + key + '@@', value)
    if '@@' in html:
        raise SystemExit('unfilled placeholder in ' + template)
    write_if_changed(target, html)
    return target


def build_data(manifest, modules, all_ids):
    """Write the manifest and module bundles. Returns the changed paths."""
    changed = []
    bundles = {
        'manifest.all.js': ('LH_MANIFEST',
                            build_manifest_js(manifest, modules, set(all_ids))),
    }
    for pid in all_ids:
        bundles['manifest.%s.js' % pid] = (
            'LH_MANIFEST', build_manifest_js(manifest, modules, {pid}))
        bundles['%s.modules.js' % pid] = ('AP_MODULES', modules[pid])

    for name, (var_name, payload) in bundles.items():
        path = os.path.join(DATA, name)
        text = BANNER + 'window.%s = %s;\n' % (
            var_name, json.dumps(payload, ensure_ascii=False, indent=2))
        if write_if_changed(path, text):
            changed.append(os.path.relpath(path, ROOT))
    return changed


def build_pages(manifest, all_ids):
    """Write the portal page, the programme pages and the flashcard pages."""
    changed = []
    site = manifest['site']

    portal = os.path.join(ROOT, 'index.html')
    render('page.html', {
        'PROGRAMME': '',
        'TITLE': site['title'],
        'DESC': site['desc'],
        'SHORT': 'Hub',
        'ROOT': '',
        'HOME': 'index.html',
        'BACKLINK': 'Programme overview',
        'DATA': 'manifest.all',
    }, portal)
    changed.append(os.path.relpath(portal, ROOT))

    for programme in manifest['programmes']:
        pid = programme['id']
        page = os.path.join(ROOT, pid, 'index.html')
        render('page.html', {
            'PROGRAMME': pid,
            'TITLE': programme['title'],
            'DESC': programme['desc'],
            'SHORT': programme['short'],
            'ROOT': '../',
            'HOME': '../index.html',
            'BACKLINK': 'All programmes',
            'DATA': 'manifest.' + pid,
        }, page)
        changed.append(os.path.relpath(page, ROOT))

        player = os.path.join(ROOT, pid, 'flashcards.html')
        render('flashcards.html', {
            'PROGRAMME': pid,
            'TITLE': programme['short'],
        }, player)
        changed.append(os.path.relpath(player, ROOT))
    return changed


def main():
    manifest, modules = collect()
    validate(manifest, modules)
    all_ids = [p['id'] for p in manifest['programmes']]

    changed = build_data(manifest, modules, all_ids)
    changed += build_pages(manifest, all_ids)

    for rel in changed:
        print('wrote', rel)
    print('%d files written' % len(changed))

    if '--check' in sys.argv:
        print('content compiles clean')


if __name__ == '__main__':
    main()
